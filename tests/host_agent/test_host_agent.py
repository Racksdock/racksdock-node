def test_host_agent_dev_guest_files_and_image_path(tmp_path):
    """Dev trust mode hands the dev CA certificates (never its private keys) and the node's simulated identity to the VM; images are
    addressed by their catalog version (<os>_<release>.qcow2)."""
    ca_dir = tmp_path / "devca"
    DevCA.create(ca_dir)
    node_dir = tmp_path / "node"
    DevCA(ca_dir).issue_node(node_dir, count=2)
    trust = TrustConfig(mode="dev", dev_ca_dir=ca_dir)
    cfg = HostAgentConfig(mode="real", state_dir=tmp_path / "state", key_path=tmp_path / "state" / "host.seed", sim_node_dir=node_dir, trust=trust)

    class NoBackend:
        name = "none"

        def host_inventory(self):
            return {}

    agent = HostAgent(cfg, backend=NoBackend())
    files = agent._dev_guest_files()
    assert "/etc/racksdock/devca/root.pem" in files and "/etc/racksdock/devca/rim.json" in files
    assert not any(k.startswith("/etc/racksdock/devca/") and k.endswith(".key") for k in files)
    assert "/etc/racksdock/node/devices/0.key" in files and "/etc/racksdock/node/inventory.json" in files
    assert "RACKSDOCK_TRUST_MODE=dev" in files["/etc/racksdock/node-agent.env"]
    cfg_prod = HostAgentConfig(mode="real", state_dir=tmp_path / "state2", key_path=tmp_path / "state2" / "host.seed", trust=TrustConfig(mode="prod", dev_ca_dir=None))
    assert HostAgent(cfg_prod, backend=NoBackend())._dev_guest_files() == {}
    src = (Path(__file__).parents[2] / "src/racksdock_node/host_agent/agent.py").read_text()
    assert 'f"{lc.image_version}.qcow2"' in src


