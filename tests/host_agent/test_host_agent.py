def test_domain_xml_has_all_passthrough_devices(tmp_path):
    res = VmResources(gpu_pci=[f"0000:{17 + i * 8:02x}:00.0" for i in range(8)], nvswitch_pci=["0000:05:00.0", "0000:06:00.0"],
                      nvme_pci=["0000:a0:00.0"], nic_vf_pci="0000:b0:00.1", vcpus=120, memory_gb=1850)
    xml = build_domain_xml("racksdock-x", res, tmp_path / "os.qcow2", tmp_path / "seed.iso", tmp_path / "nvram.fd",
                           host_cores=[list(range(4, 64)), list(range(68, 128))], bridge="br0")
    root = ET.fromstring(xml)
    hostdevs = root.findall("./devices/hostdev")
    assert len(hostdevs) == 8 + 2 + 1 + 1
    assert root.find("./cpu").get("mode") == "host-passthrough"
    assert root.find("./memoryBacking/hugepages/page").get("size") == "1048576"
    assert root.find("./devices/vsock") is not None
    assert len(root.findall("./cputune/vcpupin")) == 120
    assert root.find("./devices/interface") is None  # VF used instead of bridge
    assert root.find("./os/loader").text.endswith(".fd")
    assert parse_pci("0000:17:00.0") == ("0x0000", "0x17", "0x00", "0x0")
    plan = numa_plan(4, [[0, 1], [10, 11]])
    assert plan == [(0, 0), (1, 10), (2, 1), (3, 11)]


def test_domain_xml_lab_host_options(tmp_path):
    """Single-IP lab host: NAT network, no hugepages, virtio data disk, GeForce audio functions passed through with the GPUs."""
    res = VmResources(gpu_pci=[f"0000:{b}:00.0" for b in ("01", "25", "41", "61", "81", "a1", "c1", "e1")],
                      extra_pci=[f"0000:{b}:00.1" for b in ("01", "25", "41", "61", "81", "a1", "c1", "e1")],
                      vcpus=120, memory_gb=439, data_disk_gb=500, hugepage_kib=0)
    xml = build_domain_xml("racksdock-y", res, tmp_path / "os.qcow2", tmp_path / "seed.iso", tmp_path / "nvram.fd",
                           host_cores=[list(range(8, 128))], bridge=None, nat_network="default", data_disk=tmp_path / "data.qcow2")
    root = ET.fromstring(xml)
    assert len(root.findall("./devices/hostdev")) == 16
    assert root.find("./memoryBacking/hugepages") is None and root.find("./memoryBacking/locked") is None
    assert root.find("./devices/interface").get("type") == "network" and root.find("./devices/interface/source").get("network") == "default"
    disks = root.findall("./devices/disk[@device='disk']")
    assert [d.find("target").get("dev") for d in disks] == ["vda", "vdb"] and disks[1].find("serial").text == "racksdock-data"
    assert root.find("./cpu/numa") is None  # single NUMA node
    # production: hugepages on, wide OVMF MMIO window as a qemu fw_cfg argument
    prod = VmResources(gpu_pci=["0000:17:00.0"], memory_gb=16, pci_mmio64_mb=2048000)
    xml = build_domain_xml("racksdock-z", prod, tmp_path / "os.qcow2", tmp_path / "seed.iso", tmp_path / "nvram.fd", bridge="br0")
    assert 'xmlns:qemu="http://libvirt.org/schemas/domain/qemu/1.0"' in xml and "X-PciMmio64Mb,string=2048000" in xml
    root = ET.fromstring(xml)
    assert root.find("./memoryBacking/hugepages/page").get("size") == "1048576"


def test_nat_rules_roundtrip_through_iptables_save():
    from racksdock_node.host_agent.hypervisor.libvirt_backend import nat_rules, parse_tagged_rules

    rules = nat_rules("172.19.4.67", 20022, "192.168.122.5", "racksdock-nat-inst_1")
    assert [(t, a[0]) for t, a in rules] == [("nat", "PREROUTING"), ("nat", "OUTPUT"), ("filter", "FORWARD")]
    save = """# Generated by iptables-save
*filter
:FORWARD DROP [0:0]
-A FORWARD -d 192.168.122.5/32 -p tcp -m tcp --dport 22 -m comment --comment racksdock-nat-inst_1 -j ACCEPT
-A FORWARD -o virbr0 -j REJECT --reject-with icmp-port-unreachable
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
-A PREROUTING -p tcp -m tcp --dport 20022 -m comment --comment racksdock-nat-inst_1 -j DNAT --to-destination 192.168.122.5:22
-A OUTPUT -d 172.19.4.67/32 -p tcp -m tcp --dport 20022 -m comment --comment racksdock-nat-inst_1 -j DNAT --to-destination 192.168.122.5:22
-A POSTROUTING -s 192.168.122.0/24 -j MASQUERADE
-A PREROUTING -p tcp -m tcp --dport 20023 -m comment --comment "other tool" -j DNAT --to-destination 10.0.0.2:22
COMMIT
"""
    tagged = parse_tagged_rules(save, "racksdock-nat")
    assert [(t, a[0]) for t, a in tagged] == [("filter", "FORWARD"), ("nat", "PREROUTING"), ("nat", "OUTPUT")]
    assert parse_tagged_rules(save, "racksdock-nat-other") == []
    assert tagged[1][1][-1] == "192.168.122.5:22"


